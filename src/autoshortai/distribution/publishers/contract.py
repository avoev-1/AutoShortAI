from typing import Any, Dict, Protocol


class PublisherPlugin(Protocol):
    plugin_id: str
    platform_name: str
    capabilities: Dict[str, Any]

    def validate_account(self, account_ref: str) -> bool: ...
    def validate_asset(self, asset_ref: str, metadata: Dict[str, Any]) -> bool: ...
    def adapt_metadata(self, campaign: Any, target: Any) -> Dict[str, Any]: ...
    def publish(self, job: Dict[str, Any]) -> Dict[str, Any]: ...
    def get_status(self, publication_ref: str) -> Dict[str, Any]: ...
    def collect_analytics(self, publication_ref: str) -> Dict[str, Any]: ...
    def refresh_auth(self, account_ref: str) -> bool: ...
